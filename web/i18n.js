class I18nManager {
  constructor() {
    this.storageLangKey = 'vetassist_lang';
    this.storageCurrKey = 'vetassist_currency';
    this.currentLang = this.loadLanguage();
    this.currentCurrency = this.loadCurrency();
  }

  loadLanguage() {
    return localStorage.getItem(this.storageLangKey) || 'tr';
  }

  loadCurrency() {
    const saved = localStorage.getItem(this.storageCurrKey);
    if (saved && CURRENCIES[saved]) return saved;
    return DEFAULT_CURRENCY_FOR_LANG[this.currentLang] || 'TRY';
  }

  setLanguage(lang, autoUpdateCurrency = true) {
    if (!TRANSLATIONS[lang]) lang = 'tr';
    this.currentLang = lang;
    localStorage.setItem(this.storageLangKey, lang);
    document.documentElement.lang = lang;

    if (autoUpdateCurrency) {
      const defaultCurr = DEFAULT_CURRENCY_FOR_LANG[lang] || 'USD';
      this.currentCurrency = defaultCurr;
      localStorage.setItem(this.storageCurrKey, defaultCurr);
      const currSelect = document.getElementById('settingCurrency');
      if (currSelect) currSelect.value = defaultCurr;
    }

    this.translateDOM();

    if (window.app && typeof window.app.onLanguageChanged === 'function') {
      window.app.onLanguageChanged();
    }
    if (window.app && typeof window.app.onCurrencyChanged === 'function') {
      window.app.onCurrencyChanged();
    }
  }

  setCurrency(currCode) {
    if (!CURRENCIES[currCode]) currCode = 'TRY';
    this.currentCurrency = currCode;
    localStorage.setItem(this.storageCurrKey, currCode);

    if (window.app && typeof window.app.onCurrencyChanged === 'function') {
      window.app.onCurrencyChanged();
    }
  }

  getLanguage() {
    return this.currentLang;
  }

  getCurrency() {
    return this.currentCurrency;
  }

  getCurrencyMeta(currCode = this.currentCurrency) {
    return CURRENCIES[currCode] || CURRENCIES.TRY;
  }

  getCurrencySymbol(currCode = this.currentCurrency) {
    const meta = this.getCurrencyMeta(currCode);
    return meta ? meta.symbol : 'â‚º';
  }

  formatMoney(amount, currCode = this.currentCurrency) {
    const num = parseFloat(amount) || 0;
    const meta = this.getCurrencyMeta(currCode);
    const decimals = meta.decimals !== undefined ? meta.decimals : 2;
    const formattedNum = num.toFixed(decimals);

    if (meta.position === 'prefix') {
      return `${meta.symbol}${meta.space ? ' ' : ''}${formattedNum}`;
    } else {
      return `${formattedNum}${meta.space ? ' ' : ''}${meta.symbol}`;
    }
  }

  t(key, params = {}) {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.tr;
    let text = dict[key] || TRANSLATIONS.en[key] || TRANSLATIONS.tr[key] || key;
    
    // Replace {paramName}
    for (const [pKey, pVal] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${pKey}\\}`, 'g'), pVal);
    }
    return text;
  }

  translateDOM() {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      el.innerHTML = this.t(key);
    });

    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.setAttribute('placeholder', this.t(key));
    });

    const titles = document.querySelectorAll('[data-i18n-title]');
    titles.forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      el.setAttribute('title', this.t(key));
    });
  }
}

// Global instance
window.CURRENCIES = CURRENCIES;
window.DEFAULT_CURRENCY_FOR_LANG = DEFAULT_CURRENCY_FOR_LANG;
window.i18n = new I18nManager();

